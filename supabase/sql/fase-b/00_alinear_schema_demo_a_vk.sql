CREATE OR REPLACE FUNCTION public.rpc_tickets_marcar(p_id bigint, p_nuevo_estado text, p_atendido_por text)
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
declare
  v_estado_actual text;
begin
  if p_nuevo_estado not in ('atendido','resuelto') then
    return json_build_object('ok', false, 'error', 'Estado inválido.');
  end if;
  select estado into v_estado_actual from tickets_soporte where id = p_id;
  if v_estado_actual is null then
    return json_build_object('ok', false, 'error', 'Ticket no encontrado.');
  end if;
  if v_estado_actual = 'resuelto' then
    return json_build_object('ok', false, 'error', 'Este ticket ya está resuelto.');
  end if;
  update tickets_soporte
    set estado = p_nuevo_estado,
        atendido_por = coalesce(left(p_atendido_por, 200), atendido_por),
        atendido_at = case when p_nuevo_estado = 'resuelto' then now() else atendido_at end
    where id = p_id;
  return json_build_object('ok', true);
end;
$function$;
