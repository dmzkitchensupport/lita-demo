CREATE OR REPLACE FUNCTION public.rpc_upsert_colaborador(p_admin_email text, p_admin_pass text, p_email text, p_nombre text, p_apellido text, p_rol text, p_pass text, p_pin text, p_autoriza boolean, p_area_responsable text DEFAULT NULL::text)
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'extensions'
