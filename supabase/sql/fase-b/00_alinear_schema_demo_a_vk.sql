  v_ke text := 'email:' || lower(coalesce(p_admin_email, ''));  -- v1.1
  v_ki text := 'ip:' || _seg_ip();                                -- v1.1
begin
  -- v1.1: mismo límite que rpc_login (10 fallos / 15 min por correo del admin, 30 / 15 min por IP).
  if _seg_bloqueado('admin', v_ke, 10, interval '15 minutes')
     or _seg_bloqueado('admin', v_ki, 30, interval '15 minutes') then
    return json_build_object('ok', false, 'err', 'unauthorized', 'motivo', 'bloqueado');
  end if;
  select * into v_admin from colaboradores
   where email = lower(p_admin_email) and activo = true and rol = 'admin';
