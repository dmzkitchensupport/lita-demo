CREATE OR REPLACE FUNCTION public.rpc_login(p_email text, p_pass text)
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'extensions'
AS $function$
DECLARE u colaboradores%ROWTYPE; ke text := 'email:' || lower(coalesce(p_email, '')); ki text := 'ip:' || _seg_ip();
BEGIN
  IF _seg_bloqueado('login', ke, 10, interval '15 minutes')
     OR _seg_bloqueado('login', ki, 30, interval '15 minutes') THEN
    RETURN json_build_object('ok', false, 'motivo', 'bloqueado');
  END IF;
  SELECT * INTO u FROM colaboradores
  WHERE lower(email) = lower(p_email) AND activo = true;
  IF NOT FOUND OR u.pass_hash IS NULL OR crypt(p_pass, u.pass_hash) <> u.pass_hash THEN
    PERFORM _seg_fallo('login', ke);
    PERFORM _seg_fallo('login', ki);
    RETURN json_build_object('ok', false);
  END IF;
  RETURN json_build_object(
    'ok', true,
    'email', u.email, 'nombre', u.nombre, 'apellido', u.apellido,
    'rol', u.rol, 'puede_autorizar', u.puede_autorizar, 'hidden', u.hidden
  );
END; $function$;
