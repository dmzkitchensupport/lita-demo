CREATE OR REPLACE FUNCTION public._seg_bloqueado(p_tipo text, p_clave text, p_max integer, p_ventana interval)
 RETURNS boolean
 LANGUAGE sql
 STABLE
 SET search_path TO 'public'
AS $function$
  -- v2 (Cla): si no llega la IP, no aplicar límite por IP (evita bloqueo global de todos los usuarios)
